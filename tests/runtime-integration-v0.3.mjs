import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import {validateProposal} from '../server.mjs';
const read=async p=>readFile(new URL('../'+p,import.meta.url),'utf8');
const ctx={window:{}};
for(const f of ['website/data/operational-v0.3.generated.js','website/suitability-v0.3.js','website/runtime-adapter-v0.3.js'])vm.runInNewContext(await read(f),ctx);
const S=ctx.window.PlantscapesSuitabilityV03,A=ctx.window.PlantscapesRuntimeV03;
const fixture=JSON.parse(await read('dataset/research/demo-v0_3/example-inputs.json'));
const zone={id:1,name:'Dry test',conditions:{...fixture.zones[0],source:'demo',field_origins:{soil:'synthetic_fallback'}}};
const project={...fixture.project,area:300};
const candidates=A.candidates([zone],project);
assert.ok(candidates.length>0);
assert.ok(candidates.every(p=>p.operational&&p.productionEligible===false));
for(let i=1;i<candidates.length;i++)assert.ok(S.ranking(candidates[i-1].evaluation,candidates[i].evaluation)<=0,'v0.3 ranking order');
assert.ok(candidates.some(p=>p.evaluation.raw_suitability_score>p.evaluation.final_suitability_score&&p.evaluation.evidence_confidence_score<25));
assert.equal(A.zone(zone).source,'demo','synthetic fallback cannot become an observation');
const unknown={...zone,conditions:{...zone.conditions,soil:'unknown'}};
const result=A.evaluate(S.plants[0],unknown,project);
assert.equal(result.component_ratios.soil,0);
assert.ok(result.warnings.some(w=>w.code==='site_data_gap'));
const made=A.evaluate(S.plants[0],{...zone,conditions:{...zone.conditions,soil:'made'}},project);
assert.equal(made.component_ratios.soil,.25,'made ground is never a compatibility bypass');
const harvest=A.evaluate(S.plants[0],zone,{...project,publicHarvest:true});
assert.equal(harvest.harvesting_allowed,false);
assert.ok(harvest.warnings.some(w=>w.code==='harvesting_not_recommended'));
assert.equal(S.plants[0].invasive_status,'unknown');
const unresolvedThorns=candidates.find(p=>p.thorns==='unknown');assert.ok(unresolvedThorns&&unresolvedThorns.thorny===null);
const good=candidates.find(p=>!['Trees','Climbers','Aquatic & marginal plants'].includes(p.group));
assert.ok(good);
const bad=S.plants.find(p=>p.group==='Climbers');assert.ok(bad);
const context={version:'test/v0.3',project:JSON.parse(JSON.stringify(A.project(project,'placement'))),zones:[zone],geometry:[{type:'boundary',points:[[0,0],[20,0],[20,15],[0,15]]},{type:'planting',zoneId:1,points:[[0,0],[20,0],[20,15],[0,15]]}],species:[{id:good.id}],communities:[{id:'c1',zoneId:1,bedIndex:0,zone:'Dry test',band:'interior',shade:false,area:290,allowedIds:[good.id],rows:[{plantId:good.id,percentage:100}]}]};
const proposal={summary:'Demo.',warnings:[],changes:[{communityId:'c1',shares:[{plantId:good.id,percentage:100}]}]};
assert.equal(validateProposal(proposal,context),proposal);
assert.throws(()=>validateProposal({...proposal,changes:[{communityId:'c1',shares:[{plantId:bad.fixture_id,percentage:100}]}]},context));
assert.throws(()=>validateProposal({...proposal,changes:[{communityId:'c1',shares:[{plantId:bad.fixture_id,percentage:100}]}]},{...context,communities:[{...context.communities[0],allowedIds:[bad.fixture_id]}]}));
const app=await read('website/app.js'),server=await read('server.mjs'),engine=await read('website/planting-engine.js');
assert.ok(!app.includes('demo.plants'));
assert.ok(!server.includes('demo-data.js'));
for(const old of ['not_invasive_fixture','spread*.83','height*.42','/dominate|strongly|vigorous|thicket|suckering/i','/thorn/i'])assert.ok(!engine.includes(old),`legacy derivation ${old}`);
console.log('Passed: v0.3 candidate ranking, uncertainty, source mapping, server AI revalidation, and no legacy operational derivations.');
