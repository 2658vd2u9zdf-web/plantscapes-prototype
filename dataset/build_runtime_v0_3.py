"""Build the browser/Node v0.3 runtime bundle from authoritative, read-only inputs.

Run: python dataset/build_runtime_v0_3.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.dont_write_bytecode = True
sys.path.insert(0, str(ROOT / 'dataset/research/demo-v0_3'))
from pilot_model import load_plants  # noqa: E402

sources = {
    'plants': ROOT / 'dataset/derived/plantscapes_demo_matching_ready_v0_3.csv',
    'rules': ROOT / 'dataset/scoring/plant-suitability-rules-v0_3.json',
    'contract': ROOT / 'dataset/scoring/plant-location-contract-v0_3.json',
}
plants = load_plants(sources['plants'])
assert len(plants) == 60 and len({p['plant_id'] for p in plants}) == 60
assert all(p['production_eligible'] is False for p in plants)
payload = {
    'version': '0.3.0',
    'plants': plants,
    'rules': json.loads(sources['rules'].read_text(encoding='utf-8')),
    'contract': json.loads(sources['contract'].read_text(encoding='utf-8')),
}
out = ROOT / 'website/data/operational-v0.3.generated.js'
out.write_text('/* Generated by python dataset/build_runtime_v0_3.py. Do not edit. */\n'
               '(function(root){root.PLANTSCAPES_OPERATIONAL_V03='
               + json.dumps(payload, ensure_ascii=False, separators=(',', ':'))
               + ';})(typeof window!=="undefined"?window:globalThis);\n', encoding='utf-8')
print(f'Built {out.relative_to(ROOT)} with {len(plants)} records')
