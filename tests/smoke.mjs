import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const base=new URL('../',import.meta.url),read=path=>readFile(new URL(path,base),'utf8');
const ctx={window:{},console};
for(const file of ['website/data/catalogue.js','website/data/operational-v0.3.generated.js','website/suitability-v0.3.js','website/runtime-adapter-v0.3.js','website/data/planting-plan-rules.v0.1.js','website/planting-engine.js'])vm.runInNewContext(await read(file),ctx);
const {PlantscapesEngine:E,PlantscapesRuntimeV03:A,PlantscapesSuitabilityV03:S,PLANTSCAPES_RULEBOOK:book}=ctx.window;
assert.equal(book.review_state,'design_policy_approved_species_validation_pending');
assert.ok(ctx.window.PLANTSCAPES_CATALOGUE.length>=2400);
assert.equal(JSON.stringify(book),JSON.stringify(JSON.parse(await read('dataset/planting-plan-rules.v0.1.json'))));
const ruleIds=new Set(book.rules.map(r=>r.id)),fixture=JSON.parse(await read('dataset/research/demo-v0_3/example-inputs.json'));
const zone={id:1,name:'Dry example',conditions:fixture.zones[0]},project={...fixture.project,area:560};
const plants=A.candidates([zone],project),boundary=[[0,0],[28,0],[28,20],[0,20]];
assert.ok(plants.length>10&&plants.every(p=>p.operational&&p.productionEligible===false));
const nameOnly={id:'name-only',name:'Name only',group:'Flowers & herbs',reviewed:false};
const input={boundary,beds:[{polygon:boundary,zoneId:1}],paths:[[[14,0],[14,20]]],plants:[...plants,nameOnly],project,zones:[zone],pathWidth:1.5};
assert.match(E.generate({...input,beds:[]}).error,/Draw a planting zone/);
assert.equal(E.eligibility(nameOnly,project).eligible,false);
const result=E.generate(input);assert.ok(result.placements.length>50);
assert.ok(result.placements.every(p=>result.valid(p.xy)));
assert.ok(result.placements.every(p=>p.ruleTrace.every(id=>ruleIds.has(id))));
assert.ok(result.decisions.some(d=>d.plantId==='name-only'&&!d.eligible));
assert.ok(result.visibility.length>=2);
for(const item of result.placements.filter(p=>result.pathDistance(p.xy)<E.config.edgeDepth))assert.ok(item.height<=E.config.edgeHeight);
const pathless=E.generate({...input,paths:[]});assert.ok(pathless.placements.length>0,'paths are optional');
assert.equal(JSON.stringify(E.generate(input).placements),JSON.stringify(result.placements),'placement must be deterministic');
const mismatched={...zone,conditions:{...zone.conditions,soil:'peat',moisture:'wet',hydrology:'permanent',waterEdge:'yes'}};
const first=plants[0],mismatch=E.zoneFit(first,mismatched,project);
assert.equal(mismatch.fit,S.evaluate(S.plants.find(p=>p.fixture_id===first.id),A.zone(mismatched),A.project(project,'placement')).eligible_for_demo_ranking);
vm.runInNewContext(await read('website/plan-graphics.js'),ctx);
const graphics=ctx.window.PlantscapesGraphics;
assert.equal(new Set(Array.from({length:9},(_,i)=>graphics.pattern(i+1,'#123456','test'))).size,9);
const waterPolygon=[[2,2],[10,2],[10,14],[2,14]];
const view=graphics.elevated({boundary,sketches:[{type:'water',points:waterPolygon},{type:'open',points:[[20,2],[25,2],[25,6]]},{type:'path',points:[[14,0],[14,20]]}],placements:result.placements,plants,masses:[],keys:[],direction:'south',season:'summer',age:5,angle:'elevated',pathWidth:1.5,colours:{}});
for(const surface of ['water','open','path'])assert.ok(view.svg.includes('data-surface="'+surface+'"'));
const html=await read('website/index.html');for(const id of ['sketchZone','planNotation','mixMatrix','planRuleReview','undoPlanEdit','publicAccess','mappedSupport'])assert.ok(html.includes('id="'+id+'"'));
assert.ok(html.indexOf('id="planNotation"')<html.indexOf('id="map"'));
const app=await read('website/app.js');new vm.Script(app);assert.ok(!app.includes('demo.plants'));assert.ok(!app.includes('{color,weight'));assert.ok(!app.includes('{renderer,radius'));
console.log('Passed: v0.3 operational placement, optional paths, geometry, rendering, rulebook, name-only exclusion and deterministic preview.');
