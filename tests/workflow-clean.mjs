import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const {chromium}=createRequire(import.meta.url)('playwright');
const browser=await chromium.launch({headless:true,channel:'msedge'});
try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto((process.env.PLANTSCAPES_TEST_URL||'http://127.0.0.1:4182')+'/website/index.html?v=workflow-v03',{waitUntil:'networkidle'});
  await page.locator('#startProject').click();await page.locator('#toSite').click();
  await page.locator('#location').fill('Delft');
  await page.locator('#plotExample').click();await page.locator('#toConfirm').click();
  assert.ok(await page.locator('[data-condition-key="source"]').isVisible());
  await page.locator('#toPalette').click();assert.ok(await page.locator('#paletteGroups .plant-row').count()>5);
  await page.locator('#toReview').click();await page.locator('#toPlan').click();
  await page.evaluate(()=>{setTool('planting');state.draft=state.plotBoundary.map(p=>p.slice());drawDraft();finishShape();setTool('pan');});
  await page.locator('#generatePlan').click();
  const plan=await page.evaluate(()=>({generated:state.generated,count:state.placements.length,communityMode:state.planAudit?.communityMode,bands:state.planAudit?.communities.map(c=>c.band)}));
  assert.ok(plan.generated&&plan.count>0&&plan.communityMode,JSON.stringify(plan));
  assert.ok(plan.bands.every(x=>x==='interior'),'pathless plans must not create artificial edge bands');
  assert.ok(await page.locator('#communityControls').isVisible());
  await page.locator('.recipe-details > summary').click();
  const rows=page.locator('#communityRows input[data-recipe-species]');assert.ok(await rows.count()>0);
  const count=await rows.count();for(let i=0;i<count;i++)await rows.nth(i).fill(i===0?'100':'0');
  page.once('dialog',d=>d.accept());await page.locator('#applyRecipe').click();
  const recipeState=await page.evaluate(()=>({percentage:state.planAudit.communities[0].rows[0].percentage,status:field('recipeStatus').textContent,generation:field('generationStatus').textContent,overrides:state.recipeOverrides,revision:state.planRevision}));
  assert.equal(recipeState.percentage,100,JSON.stringify(recipeState));
  page.once('dialog',d=>d.accept());await page.locator('#undoRecipe').click();
  const dense=await page.evaluate(()=>PlantscapesDenseView().length);assert.ok(dense>0);
  await page.locator('#toCamera').click();assert.equal(await page.evaluate(()=>state.stage),8);
  assert.ok(await page.locator('#cameraPlan').isVisible());assert.ok(await page.locator('#exportScene').isVisible());
  await page.setViewportSize({width:375,height:850});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  assert.deepEqual(errors,[]);
  console.log('Passed: v0.3 pathless workflow, visible evidence, editable/undoable community recipe, dense preview, camera and mobile layout.');
}finally{await browser.close();}
