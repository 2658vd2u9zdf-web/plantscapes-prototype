/* Before/after comparison of two recommender-audit snapshots, written as Markdown.
   Run: node tests/recommender-audit-compare.mjs <before.json> <after.json> <out.md> */
import {readFile,writeFile} from 'node:fs/promises';

const [beforeFile,afterFile,out]=process.argv.slice(2);
if(!out)throw Error('Usage: node tests/recommender-audit-compare.mjs <before.json> <after.json> <out.md>');
const before=JSON.parse(await readFile(beforeFile,'utf8')),after=JSON.parse(await readFile(afterFile,'utf8'));
const lines=[`# Recommender before/after comparison`,'',`Generated by \`tests/recommender-audit-compare.mjs\` from \`${beforeFile.split(/[\\/]/).pop()}\` (rules ${before.rules_version}) and \`${afterFile.split(/[\\/]/).pop()}\` (rules ${after.rules_version}). Benchmark ${after.benchmark_version}. All scenarios are synthetic; nothing here is a planting recommendation.`,''];
const states=['conditional_match','unsuitable','data_gap','excluded'];
lines.push('## Eligibility-state counts per case','','| Case | '+states.map(s=>s+' (before → after)').join(' | ')+' | JS/Python parity mismatches (before → after) |','|---|'+states.map(()=>'---:').join('|')+'|---:|');
for(const [id,a] of Object.entries(after.cases)){const b=before.cases[id];lines.push('| '+id+' | '+states.map(s=>(b.counts[s]||0)+' → '+(a.counts[s]||0)).join(' | ')+' | '+b.parity.mismatches+' → '+a.parity.mismatches+' |');}
lines.push('','## Records whose eligibility state, final score or raw score changed','');
let changed=0;
for(const [id,a] of Object.entries(after.cases)){
  const b=before.cases[id],rows=Object.entries(a.rows).filter(([f,r])=>r.state!==b.rows[f].state||r.final!==b.rows[f].final||r.raw!==b.rows[f].raw);
  if(!rows.length)continue;changed+=rows.length;
  lines.push(`**${id}** (${rows.length})`,'');
  const groups={};for(const [f,r] of rows){const k=b.rows[f].state+' '+b.rows[f].final+' → '+r.state+' '+r.final;(groups[k]||=[]).push(r.name);}
  for(const [k,names] of Object.entries(groups))lines.push('- '+k+': '+names.join(', '));
  lines.push('');
}
if(!changed)lines.push('None.','');
lines.push('## Gate states that changed (count of records per transition)','','| Case | Gate | before → after | Records |','|---|---|---|---:|');
for(const [id,a] of Object.entries(after.cases)){
  const b=before.cases[id],t={};
  for(const [f,r] of Object.entries(a.rows)){
    for(const g of new Set([...Object.keys(r.gates),...Object.keys(b.rows[f].gates)])){
      const x=b.rows[f].gates[g]||(g==='H12_MAINTENANCE_CAPACITY'?'absent':'passed'),y=r.gates[g]||'passed';if(x!==y){const k=g+'|'+x+' → '+y;t[k]=(t[k]||0)+1;}
    }
  }
  for(const [k,n] of Object.entries(t).sort()){const [g,s]=k.split('|');lines.push(`| ${id} | ${g} | ${s} | ${n} |`);}
}
lines.push('','## Ranking changes (top 10 eligible, before vs after)','');
for(const [id,a] of Object.entries(after.cases)){
  const b=before.cases[id];if(JSON.stringify(a.ranking)===JSON.stringify(b.ranking))continue;
  const name=f=>a.rows[f].name+(b.rows[f]?'':'');
  lines.push(`**${id}**: ${b.ranking.length} → ${a.ranking.length} eligible`,'','| # | Before | After |','|---:|---|---|');
  for(let i=0;i<Math.min(10,Math.max(a.ranking.length,b.ranking.length));i++)lines.push(`| ${i+1} | ${b.ranking[i]?name(b.ranking[i]):''} | ${a.ranking[i]?name(a.ranking[i]):''} |`);
  const moved=a.ranking.map((f,i)=>[f,b.ranking.indexOf(f)-i]).filter(([,d])=>Math.abs(d)>=5).map(([f,d])=>a.rows[f].name+' '+(d>0?'+':'')+d);
  if(moved.length)lines.push('','Moved five or more places: '+moved.join(', ')+'.');
  lines.push('');
}
lines.push('## Community consequences','');
for(const [id,a] of Object.entries(after.cases)){
  if(!a.community)continue;const b=before.cases[id].community;
  const diff=Object.keys(a.community.consequence).filter(f=>JSON.stringify(a.community.consequence[f])!==JSON.stringify(b.consequence[f]));
  lines.push(`**${id}**: ${b.communities.length} → ${a.community.communities.length} communities; share basis declared: ${[...new Set(a.community.communities.map(c=>c.shareBasis))].join(', ')||'none'}; membership changes: ${diff.length?diff.map(f=>a.rows[f].name).join(', '):'none'}.`);
  for(const c of a.community.communities.slice(0,2)){
    const woody=c.rows.filter(r=>a.rows[r.id].group==='Shrubs');
    if(woody.length)lines.push(`- ${c.band}${c.shade?' (under canopy)':''}: ${c.species} species, ${c.total} plants on ${c.area} m². Shrubs hold ${woody.reduce((n,r)=>n+r.pct,0).toFixed(1)}% of plant count but ${woody.reduce((n,r)=>n+(r.areaPct||0),0).toFixed(1)}% of the synthetic spacing footprint.`);
  }
}
await writeFile(out,lines.join('\n')+'\n');
console.log(JSON.stringify({out,changedRecords:changed}));
